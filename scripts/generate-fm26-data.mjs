import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const SOURCE_DIR = join(ROOT, 'scripts', 'fm26-source');
const OUT_DIR = join(ROOT, 'src', 'data', 'fm26');

const PITCH_W = 76.19;
const SITE_UNITS = 100;
const COORDINATE_DECIMALS = 5;
const AM_LEFT_BELOW = 35;
const AM_RIGHT_ABOVE = 65;
const EXPECTED_ROLES = { in: 41, out: 35 };
const EXPECTED_FORMATIONS = 12;

const FIXED_SLOT_FAMILY = {
  GK: 'GK',
  DL: 'D(L)',
  DCL: 'D(C)',
  DC: 'D(C)',
  DCR: 'D(C)',
  DR: 'D(R)',
  WBL: 'WB(L)',
  WBR: 'WB(R)',
  DM: 'DM',
  DML: 'DM',
  DMR: 'DM',
  DMCL: 'DM',
  DMCR: 'DM',
  MCL: 'M(C)',
  MCR: 'M(C)',
  STL: 'ST',
  ST: 'ST',
  STR: 'ST',
};

const HEADER =
  '// Auto-generated by scripts/generate-fm26-data.mjs from scripts/fm26-source. Do not edit by hand.\n';

function fail(message) {
  throw new Error(`generate-fm26-data: ${message}`);
}

function tableRows(lines) {
  return lines
    .filter((line) => line.startsWith('|'))
    .slice(2)
    .map((line) =>
      line
        .split('|')
        .slice(1, -1)
        .map((cell) => cell.trim()),
    );
}

function unquote(cell) {
  const match = /^`([^`]+)`$/.exec(cell);
  if (!match) fail(`expected a backticked value, got "${cell}"`);
  return match[1];
}

function expandPosition(token) {
  const pair = /^([A-Z]+)\(L\/R\)$/.exec(token);
  if (pair) return [`${pair[1]}(L)`, `${pair[1]}(R)`];
  return [token];
}

function parseFamilies(cell) {
  return [...new Set(cell.split(' / ').flatMap((token) => expandPosition(token.trim())))];
}

function sectionLines(text, heading) {
  const lines = text.split('\n');
  const start = lines.findIndex((line) => line.trim() === heading);
  if (start === -1) fail(`missing section "${heading}"`);
  const next = lines.findIndex((line, index) => index > start && line.startsWith('## '));
  return lines.slice(start + 1, next === -1 ? undefined : next);
}

function parseRoles() {
  const text = readFileSync(join(SOURCE_DIR, 'fm26-role-descriptions.md'), 'utf8');
  const sections = [
    ['## In possession (IP)', 'in', 'i'],
    ['## Out of possession (OOP)', 'out', 'o'],
  ];
  const roles = sections.flatMap(([heading, possession, prefix]) => {
    const rows = tableRows(sectionLines(text, heading));
    if (rows.length !== EXPECTED_ROLES[possession]) {
      fail(`${possession} roles: expected ${EXPECTED_ROLES[possession]}, found ${rows.length}`);
    }
    return rows.map(([id, name, positions, description], index) => ({
      id: unquote(id),
      code: `${prefix}${String(index + 1).padStart(2, '0')}`,
      name,
      possession,
      families: parseFamilies(positions),
      description,
    }));
  });
  if (new Set(roles.map((role) => role.id)).size !== roles.length) fail('duplicate role ids');
  return roles;
}

function amFamilyFromX(siteX) {
  if (siteX < AM_LEFT_BELOW) return 'AM(L)';
  if (siteX > AM_RIGHT_ABOVE) return 'AM(R)';
  return 'AM(C)';
}

function deriveFamily(slotId, siteX) {
  return slotId.startsWith('AM') ? amFamilyFromX(siteX) : FIXED_SLOT_FAMILY[slotId];
}

function toPitchX(siteX) {
  return Number(((siteX * PITCH_W) / SITE_UNITS).toFixed(COORDINATE_DECIMALS));
}

function parseSlot([cellId, cellFamily, cellX, cellY], formationId) {
  const id = unquote(cellId);
  const siteX = Number(cellX);
  const y = Number(cellY);
  const family = deriveFamily(id, siteX);
  if (!family) fail(`${formationId}: unknown slot id ${id}`);
  if (family !== cellFamily) {
    fail(`${formationId}: slot ${id} derives ${family} but the table says ${cellFamily}`);
  }
  if (Number.isNaN(siteX) || Number.isNaN(y)) fail(`${formationId}: bad coordinates for ${id}`);
  return { id, family, base: { x: toPitchX(siteX), y } };
}

function parseFormations() {
  const text = readFileSync(join(SOURCE_DIR, 'fm26-formations.md'), 'utf8');
  const lines = sectionLines(text, '## 3. Slots per formation');
  const headings = lines
    .map((line, index) => ({ match: /^### \d+\. (.+) \(`([^`]+)`\)$/.exec(line), index }))
    .filter((entry) => entry.match);
  const formations = headings.map(({ match, index }, position) => {
    const end = headings[position + 1]?.index ?? lines.length;
    const id = match[2];
    const slots = tableRows(lines.slice(index + 1, end)).map((row) => parseSlot(row, id));
    return { id, name: match[1], slots };
  });
  if (formations.length !== EXPECTED_FORMATIONS) {
    fail(`expected ${EXPECTED_FORMATIONS} formations, found ${formations.length}`);
  }
  return formations;
}

function emitFile(fileName, typeName, constName, body) {
  const source = `${HEADER}import type { ${typeName} } from '../types';\n\nexport const ${constName}: readonly ${typeName}[] = ${body};\n`;
  const path = join(OUT_DIR, fileName);
  writeFileSync(path, source);
  return path;
}

function formationLiteral(formation) {
  const slots = formation.slots.map((slot) => `    ${JSON.stringify(slot)},`).join('\n');
  return `  {\n    "id": ${JSON.stringify(formation.id)},\n    "name": ${JSON.stringify(formation.name)},\n    "slots": [\n${slots}\n    ],\n  }`;
}

const formationsBody = `[\n${parseFormations().map(formationLiteral).join(',\n')},\n]`;
const written = [
  emitFile('roles.ts', 'RoleDef', 'ROLES', JSON.stringify(parseRoles(), null, 2)),
  emitFile('formations.ts', 'FormationDef', 'FORMATIONS', formationsBody),
];
execFileSync('npx', ['prettier', '--write', ...written], { cwd: ROOT, stdio: 'inherit' });
