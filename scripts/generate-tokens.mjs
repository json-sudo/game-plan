import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const SOURCE_PATH = resolve(ROOT, 'design/tokens.json');
const TOKENS_PATH = resolve(ROOT, 'src/shared/styles/tokens.scss');
const BREAKPOINTS_PATH = resolve(ROOT, 'src/shared/styles/_breakpoints.scss');
const THEMES = ['light', 'dark'];
const HEADER = '// Generated by scripts/generate-tokens.mjs from design/tokens.json. Do not edit.';
const ALIAS = /^\{([a-z0-9-]+)\}$/;

function resolveValue(value) {
  const alias = ALIAS.exec(value);
  return alias ? `var(--${alias[1]})` : value;
}

function isThemed(token) {
  return typeof token.value === 'object' && token.value !== null;
}

function tokenGroups(source) {
  return Object.values(source).filter((group) => group && Array.isArray(group.tokens));
}

function declaration(name, value) {
  return `    --${name}: ${resolveValue(value)};`;
}

function themeMixin(source, theme) {
  const lines = tokenGroups(source)
    .flatMap((group) => group.tokens)
    .filter(isThemed)
    .map((token) => declaration(token.name, token.value[theme]));
  return [`@mixin theme-${theme} {`, ...lines, '}'].join('\n');
}

function typeDeclarations(source) {
  const { families, groups } = source.type;
  const familyLines = Object.entries(families).map(([key, stack]) =>
    declaration(`font-${key}`, stack),
  );
  const styleLines = groups.flatMap((group) =>
    group.styles.flatMap((style) => {
      const font = `${style.fontWeight} ${style.fontSize}/${style.lineHeight} var(--font-${group.family})`;
      const lines = [declaration(`type-${style.name}`, font)];
      if (style.letterSpacing) {
        lines.push(declaration(`type-${style.name}-letter-spacing`, style.letterSpacing));
      }
      return lines;
    }),
  );
  return [...familyLines, ...styleLines];
}

function staticDeclarations(source) {
  return tokenGroups(source)
    .flatMap((group) => group.tokens)
    .filter((token) => !isThemed(token))
    .map((token) => declaration(token.name, token.value));
}

export function buildTokenFiles(source) {
  const breakpoint = source.size.tokens.find((token) => token.name === 'bp-phone');
  const tokens = [
    HEADER,
    '',
    ...THEMES.flatMap((theme) => [themeMixin(source, theme), '']),
    ':root {',
    ...typeDeclarations(source),
    ...staticDeclarations(source),
    '}',
    '',
    ":root,\n:root[data-theme='light'] {",
    '    @include theme-light;',
    '}',
    '',
    ":root[data-theme='dark'] {",
    '    @include theme-dark;',
    '}',
    '',
    '@media (prefers-color-scheme: dark) {',
    "    :root:not([data-theme='light']) {",
    '        @include theme-dark;',
    '    }',
    '}',
    '',
  ].join('\n');
  const breakpoints = [HEADER, '', `$phone-max: ${breakpoint.value};`, ''].join('\n');
  return { tokens, breakpoints };
}

export function generateTokens() {
  const source = JSON.parse(readFileSync(SOURCE_PATH, 'utf8'));
  const { tokens, breakpoints } = buildTokenFiles(source);
  writeFileSync(TOKENS_PATH, tokens);
  writeFileSync(BREAKPOINTS_PATH, breakpoints);
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  generateTokens();
}
